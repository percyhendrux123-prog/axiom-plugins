#!/usr/bin/env python3
"""Re-render each plugin icon as a 1-bit ordered-dither mark (ink on transparent).

Reads  docs/icons/<icon>.png      (the original line-art icons, left untouched)
Writes docs/icons/1bit/<icon>.png (64x64, ink #121316 on transparent, shown at 2x, pixelated)
       docs/assets/bits.js        (the same bits, so the page can ink them in on scroll)

Stone strokes become solid ink; the brass accent becomes a stipple, so the
two-tone icon survives in one colour. 8x8 Bayer matrix, no randomness: the
output is identical on every run.

Needs Pillow:  env -u PYTHONPATH /usr/bin/python3 scripts/dither_icons.py
(build.py does not need it; it only embeds the files this script wrote.)
"""
import base64
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / "data" / "plugins.json").read_text())
N = 64                       # output size in pixels
CROP = (20, 20, 172, 172)    # trim the empty margin of the 192px originals
INK = (18, 19, 22, 255)


def bayer(n):
    return [[0]] if n == 1 else _expand(bayer(n // 2))


def _expand(m):
    n = len(m)
    out = [[0] * (2 * n) for _ in range(2 * n)]
    for y in range(n):
        for x in range(n):
            v = 4 * m[y][x]
            out[y][x] = v
            out[y][x + n] = v + 2
            out[y + n][x] = v + 3
            out[y + n][x + n] = v + 1
    return out


B8 = bayer(8)
THR = [[(v + 0.5) / 64 for v in row] for row in B8]


def masks(img):
    """Split the icon into stone strokes and brass accent, each as coverage 0..1 at N x N."""
    rgb = img.convert("RGB").crop(CROP)
    w, h = rgb.size
    stone = Image.new("L", (w, h))
    brass = Image.new("L", (w, h))
    sp, bp = stone.load(), brass.load()
    src = rgb.load()
    for y in range(h):
        for x in range(w):
            r, g, b = src[x, y]
            lum = (r * 299 + g * 587 + b * 114) / 1000
            warm = r - b
            if warm > 30 and lum > 45:
                bp[x, y] = 255
            elif lum > 110:
                sp[x, y] = 255
    return (list(stone.resize((N, N), Image.BOX).getdata()),
            list(brass.resize((N, N), Image.BOX).getdata()))


def main():
    (ROOT / "docs" / "icons" / "1bit").mkdir(parents=True, exist_ok=True)
    bits = {}
    for name, p in DATA["plugins"].items():
        src = Image.open(ROOT / "docs" / "icons" / p["icon"]).convert("RGB")
        stone, brass = masks(src)
        im = Image.new("RGBA", (N, N), (0, 0, 0, 0))
        px = im.load()
        packed = bytearray(N * N // 8)
        for i in range(N * N):
            y, x = divmod(i, N)
            # stone: solid wherever a stroke covers a third of the pixel (thin lines stay whole)
            # brass: stipple, about half density
            on = stone[i] / 255 > 0.33 or (brass[i] / 255) * 0.62 > THR[y % 8][x % 8]
            if on:
                px[x, y] = INK
                packed[i >> 3] |= 0x80 >> (i & 7)
        im.save(ROOT / "docs" / "icons" / "1bit" / p["icon"], optimize=True)
        bits[name] = base64.b64encode(bytes(packed)).decode()
    js = ("/* Generated by scripts/dither_icons.py. 64x64 1-bit marks, row-major, MSB first, base64. */\n"
          "window.AXIOM_BITS=" + json.dumps(bits, separators=(",", ":")) + ";\n")
    (ROOT / "docs" / "assets").mkdir(exist_ok=True)
    (ROOT / "docs" / "assets" / "bits.js").write_text(js)
    print("dithered", len(bits), "icons")


if __name__ == "__main__":
    main()
